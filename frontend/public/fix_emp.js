function escapeRegex(text) {
  return text.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

function replaceAll(content, rules) {
  let out = content;
  for (const [from, to] of rules) {
    out = out.split(from).join(to);
  }
  return out;
}

